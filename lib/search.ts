/**
 * Name matching for Indian place names.
 *
 * Plain substring matching fails constantly here because the same name has many
 * romanisations: someone types "yesvan" for Yeshwantpur, "vivek nagar" for
 * Vivekananda, "krishnarajapura" for "Krishna Raja Pura". Normalising the
 * common transliteration variants before comparing makes those match.
 */

/**
 * Collapses the spelling variants that differ between romanisations of the same
 * Kannada/Sanskrit sound. Order matters: digraphs are folded before the single
 * letters they contain.
 */
export function normalizeName(input: string): string {
  return input
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')   // strip accents
    .replace(/[^a-z0-9]/g, '')          // punctuation and spaces carry no signal
    // The conjunct jna is romanised both ways: Jnanabharathi / Gnanabharathi.
    .replace(/jn/g, 'gn')
    // Aspirated consonants are written with or without the h.
    .replace(/kh/g, 'k')
    .replace(/gh/g, 'g')
    .replace(/ch/g, 'c')
    .replace(/jh/g, 'j')
    .replace(/th/g, 't')
    .replace(/dh/g, 'd')
    .replace(/ph/g, 'f')
    .replace(/bh/g, 'b')
    .replace(/sh/g, 's')
    // v and w are used interchangeably: Yeshwantpur / Yesvantpur.
    .replace(/w/g, 'v')
    // Long vowels are doubled inconsistently: Naagarbhaavi / Nagarbhavi.
    .replace(/aa/g, 'a')
    .replace(/ee/g, 'i')
    .replace(/ii/g, 'i')
    .replace(/oo/g, 'u')
    .replace(/uu/g, 'u')
    .replace(/y$/g, 'i')
    // Any remaining doubled letter is a spelling choice, not a distinction.
    .replace(/(.)\1+/g, '$1');
}

/**
 * Dice coefficient over character trigrams.
 *
 * Shared with the bus-stop search, which needs the same tolerance for the
 * same reason: normalising spelling only folds letters that correspond, and
 * it cannot bridge a whole inserted syllable — Baiyappanahalli against
 * "byappanahalli", or Yeshwantpur against BMTC's "Yeshwanthapura".
 */
export function similarity(a: string, b: string): number {
  if (a.length < 3 || b.length < 3) return a === b ? 1 : 0;
  const grams = (x: string) => {
    const set = new Set<string>();
    for (let i = 0; i < x.length - 2; i += 1) set.add(x.slice(i, i + 3));
    return set;
  };
  const A = grams(a);
  const B = grams(b);
  let shared = 0;
  for (const g of A) if (B.has(g)) shared += 1;
  return (2 * shared) / (A.size + B.size);
}

/**
 * Names Bengaluru actually uses that share no letters with the official one.
 *
 * Not spelling variants — no amount of folding turns Ulsoor into Halasuru —
 * so they cannot be derived and have to be written down. Kept deliberately
 * short: only names where the colloquial form is what people would type.
 */
const ALIASES: Array<[string, string]> = [
  ['ulsoor', 'Halasuru'],
  ['krpuram', 'Krishnarajapura'],
  ['krpura', 'Krishnarajapura'],
  ['kpuram', 'Krishnarajapura'],
  ['cityrailwaystation', 'Krantivira Sangolli Rayanna'],
  ['majesticrailway', 'Krantivira Sangolli Rayanna'],
  ['kempegowdabusstation', 'Nadaprabhu Kempegowda'],
  ['vidhanasoudha', 'Vidhana Soudha'],
  ['centralcollege', 'Central College'],
  ['bangaloreuniversity', 'Jnanabharathi'],
];

/**
 * Keys that let an initialism find a station: "mg road" to Mahatma Gandhi
 * Road, "jp nagar" to Jaya Prakash Nagar, "rv road" to Rashtreeya Vidyalaya
 * Road. These are how the stations are actually referred to, and plain
 * substring matching cannot reach them from any amount of normalising.
 *
 * Generated by reducing each leading run of words to initials and keeping
 * the rest whole, which produces both "mgroad" and "mgr".
 */
function abbreviationKeys(name: string): string[] {
  const words = name
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, ' ')
    .split(/\s+/)
    .filter(Boolean);
  if (words.length < 2) return [];

  const keys: string[] = [];
  // All initials: "mgr".
  keys.push(words.map((w) => w[0]).join(''));
  // Leading initials plus the remaining words: "mgroad", "mahatmagroad".
  for (let i = 1; i < words.length; i += 1) {
    keys.push(words.slice(0, i).map((w) => w[0]).join('') + words.slice(i).join(''));
  }
  return keys.map(normalizeName).filter((k) => k.length >= 2);
}

export interface Named {
  name: string;
  /** Kannada name, matched as-is when the query is in Kannada script. */
  nameKn?: string;
}

/** Any Kannada codepoint. */
const KANNADA = /[\u0C80-\u0CFF]/;

/**
 * Ranked name search. Prefix matches beat interior matches, and shorter names
 * beat longer ones, so "indira" surfaces Indiranagar above
 * "Indiranagar Police Station".
 */
export function matchByName<T extends Named>(items: T[], query: string, limit = 8): T[] {
  const q = normalizeName(query);
  // A Kannada query normalises away entirely, so the length guard is applied
  // to the raw string when the script is Kannada.
  if (q.length < 2 && !KANNADA.test(query)) return [];

  /*
    A Kannada query is matched against the Kannada name directly.

    normalizeName() exists to fold the many Latin transliterations of one
    name together and strips anything outside [a-z0-9], so a Kannada query
    normalises to the empty string and would otherwise match everything.
    Kannada has no transliteration ambiguity to fold, so a plain substring
    on the raw script is both correct and simpler.
  */
  const kannadaQuery = KANNADA.test(query) ? query.trim() : null;

  // A colloquial name is redirected to the official one before matching.
  const alias = ALIASES.find(([from]) => normalizeName(from) === q);
  const needle = alias ? normalizeName(alias[1]) : q;

  const scored: Array<{ item: T; rank: number; at: number }> = [];
  for (const item of items) {
    if (kannadaQuery) {
      const at = item.nameKn ? item.nameKn.indexOf(kannadaQuery) : -1;
      if (at < 0) continue;
      scored.push({ item, rank: at === 0 ? 0 : 1, at });
      continue;
    }
    const n = normalizeName(item.name);
    const at = n.indexOf(needle);
    if (at >= 0) {
      scored.push({ item, rank: at === 0 ? 0 : 1, at });
      continue;
    }
    // "mg road" can only reach Mahatma Gandhi Road this way.
    if (abbreviationKeys(item.name).some((k) => k.startsWith(needle))) {
      scored.push({ item, rank: 2, at: 0 });
    }
  }

  if (scored.length > 0) {
    return scored
      .sort((a, b) =>
        a.rank - b.rank ||
        a.at - b.at ||
        a.item.name.length - b.item.name.length ||
        a.item.name.localeCompare(b.item.name))
      .slice(0, limit)
      .map((s) => s.item);
  }

  /*
    Nothing matched literally. Spelling variants that normalising cannot
    reach — "jaynagar", "byappanahalli", "banshankari" — all returned an
    empty list, which reads as "no such station" about stations that exist.
    Cheap here regardless: there are 83 of them.
  */
  if (kannadaQuery) return [];
  return items
    .map((item) => ({ item, score: similarity(needle, normalizeName(item.name)) }))
    .filter((e) => e.score >= 0.45)
    .sort((a, b) => b.score - a.score || a.item.name.length - b.item.name.length)
    .slice(0, limit)
    .map((e) => e.item);
}
